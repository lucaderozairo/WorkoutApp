function s(
  dateIso: string,
  warmupKg: number,
  working: [number, number, true?][],
): ExerciseSetEntry {
  return {
    date: d(dateIso),
    sets: [
      { weightKg: warmupKg, reps: 5, isWarmup: true },
      ...working.map(([kg, reps, failed]) => ({
        weightKg: kg, reps, isWarmup: false, ...(failed ? { failed: true } : {}),
      })),
    ],
  };
}

